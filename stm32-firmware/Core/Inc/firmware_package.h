#ifndef FIRMWARE_PACKAGE_H
#define FIRMWARE_PACKAGE_H

#include <stddef.h>
#include <stdint.h>

#define STM32_PACKAGE_HEADER_SIZE 512U
#define STM32_PACKAGE_SLOT_SIZE 0x60000U
#define STM32_PACKAGE_MAX_IMAGE_SIZE \
    (STM32_PACKAGE_SLOT_SIZE - STM32_PACKAGE_HEADER_SIZE)
#define STM32_PACKAGE_SIGNED_HEADER_SIZE 68U
#define STM32_PACKAGE_SIGNATURE_SIZE 64U
#define STM32_PACKAGE_SIGNATURE_OFFSET STM32_PACKAGE_SIGNED_HEADER_SIZE
#define STM32_PACKAGE_PAYLOAD_OFFSET STM32_PACKAGE_HEADER_SIZE
#define STM32_PACKAGE_APP_SLOT_ADDRESS 0x08020000U
#define STM32_PACKAGE_APP_VECTOR_ADDRESS \
    (STM32_PACKAGE_APP_SLOT_ADDRESS + STM32_PACKAGE_HEADER_SIZE)
#define STM32_PACKAGE_FORMAT_VERSION 1U

typedef enum {
    STM32_PACKAGE_VALID = 0,
    STM32_PACKAGE_INVALID_HEADER,
    STM32_PACKAGE_INVALID_SIGNATURE,
    STM32_PACKAGE_INVALID_DIGEST,
    STM32_PACKAGE_INVALID_VECTOR
} stm32_package_status_t;

stm32_package_status_t stm32_package_verify(
    const uint8_t *package,
    size_t package_size,
    uint32_t *initial_stack_pointer,
    uint32_t *reset_handler);

#endif
